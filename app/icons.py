def svg(name: str, color: str, width: float = 2.0, fill: str = "none") -> bytes:
    body = P.get(name, P["info"])
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="{fill}" stroke="{color}" '
            f'stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>').encode()


def pixmap(name: str, color: str, size: int = 18, fill: str = "none", dpr: float = 2.0) -> QPixmap:
    pm = QPixmap(int(size * dpr), int(size * dpr))
    pm.fill(Qt.GlobalColor.transparent)
    r = QSvgRenderer(QByteArray(svg(name, color, fill=fill)))
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    r.render(p, QRectF(0, 0, size * dpr, size * dpr))
    p.end()
    pm.setDevicePixelRatio(dpr)
    return pm


def icon(name: str, color: str, size: int = 18, fill: str = "none") -> QIcon:
    return QIcon(pixmap(name, color, size, fill))


_APP_PM = {}


def _app_base() -> QPixmap:
    if "pm" not in _APP_PM:
        from .paths import asset
        pm = QPixmap(str(asset("icon_1024.png")))
        if pm.isNull():
            pm = QPixmap(str(asset("icon.png")))
        _APP_PM["pm"] = pm
    return _APP_PM["pm"]


def app_icon(color: str = "#7C5CFF", running: bool | None = None) -> QIcon:
    """Иконка программы (облако); точка в углу: зелёная — активен, серая — остановлен."""
    ic = QIcon()
    base = _app_base()
    for s in (16, 20, 24, 32, 40, 48, 64, 128, 256):
        pm = QPixmap(s, s)
        pm.fill(Qt.GlobalColor.transparent)
        p = QPainter(pm)
        p.setRenderHint(QPainter.RenderHint.Antialiasing)
        p.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
        if not base.isNull():
            p.drawPixmap(pm.rect(), base.scaled(s, s, Qt.AspectRatioMode.KeepAspectRatio,
                                                Qt.TransformationMode.SmoothTransformation))
        else:
            QSvgRenderer(QByteArray(svg("shield", color, width=2.2, fill=color))).render(p, QRectF(0, 0, s, s))
        if running is not None:
            d = s * .36
            p.setPen(Qt.PenStyle.NoPen)
            p.setBrush(QColor("#22C55E" if running else "#9CA3AF"))
            p.drawEllipse(QRectF(s - d, s - d, d, d))
        p.end()
        ic.addPixmap(pm)
    return ic
